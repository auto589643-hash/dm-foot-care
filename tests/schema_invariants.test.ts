assert.match(verification, /has_table_privilege\('anon', 'private\.ai_accuracy_pairs', 'SELECT'\)/)
assert.match(verification, /has_table_privilege\('anon', 'private\.ai_accuracy_summary', 'SELECT'\)/)

console.log('Schema invariant tests passed')
